/** Localise automatiquement les mentions d'unités dans le champ `price` unique. */
export function localizePriceString(
  price: string | undefined,
  locale: Locale,
): string | undefined {
  if (!price || locale === "fr") return price;
  const u = UNIT_TRANSLATIONS[locale];
  return price
    .replace(/\(bouteille\)/gi, u.bottleParen)
    .replace(/les 6\s*:/gi, u.pcs6)
    .replace(/les 12\s*:/gi, u.pcs12)
    .replace(/1 boule\s*:/gi, u.scoop1)
    .replace(/2 boules\s*:/gi, u.scoop2)
    .replace(/3 boules\s*:/gi, u.scoop3)
    .replace(/Sirop/g, u.syrup);
}

/** Localise automatiquement les colonnes de contenances (ex. Bouteille → Bottle/Botella/Bottiglia/Flasche). */
export function localizePriceColumns(
  cols: string[] | undefined,
  locale: Locale,
): string[] | undefined {
  if (!cols || locale === "fr") return cols;
  const u = UNIT_TRANSLATIONS[locale];
  return cols.map((c) => c.replace(/^Bouteille$/i, u.bottleCol));
}

/**
 * Si un texte français (intro ou sous-titre) contient un tarif unique en € (ex. « Sans alcool — 7.8€ »)
 * et que l'éditeur a modifié ce tarif uniquement côté FR dans Sanity, répercute automatiquement
 * le nouveau tarif dans la traduction EN/ES/IT/DE !
 */
export function syncEmbeddedPrice(
  frText: string | undefined,
  translatedText: string | undefined,
): string | undefined {
  if (!translatedText) return frText;
  if (!frText) return translatedText;
  const priceRe = /\d+(?:[.,]\d+)?\s*€/g;
  const frMatches = frText.match(priceRe);
  const trMatches = translatedText.match(priceRe);
  if (frMatches?.length === 1 && trMatches?.length === 1 && frMatches[0] !== trMatches[0]) {
    return translatedText.replace(priceRe, frMatches[0]);
  }
  return translatedText;
}

export function pickMenuTranslation(
  obj: Record<string, unknown>,
  baseKey: string,
  locale: Locale,
  fallbackObj?: Record<string, unknown>,
): string | undefined {
  const frVal = (obj[baseKey] as string | undefined)?.trim();
  if (locale === "fr") return frVal;

  const direct = (obj[`${baseKey}_${locale}`] as string | undefined)?.trim();
  if (direct) return syncEmbeddedPrice(frVal, direct);

  const fromFallback = (fallbackObj?.[`${baseKey}_${locale}`] as string | undefined)?.trim();
  if (fromFallback) return syncEmbeddedPrice(frVal, fromFallback);

  const enFallback =
    (obj[`${baseKey}_en`] as string | undefined)?.trim() ||
    (fallbackObj?.[`${baseKey}_en`] as string | undefined)?.trim();
  if (enFallback) return syncEmbeddedPrice(frVal, enFallback);

  return frVal;
}

export function resolveFallbackMenu(locale: Locale = "fr"): MenuCategoryData[] {
  return FALLBACK_MENU_RAW.map((cat) => ({
    _id: cat._id,
    title:
      pickMenuTranslation(cat as unknown as Record<string, unknown>, "title", locale) ??
      cat.title,
    order: cat.order,
    column: cat.column,
    intro: pickMenuTranslation(cat as unknown as Record<string, unknown>, "intro", locale),
    priceColumns: localizePriceColumns(cat.priceColumns, locale),
    singlePrice: cat.singlePrice,
    items: cat.items.map((item) => ({
      kind: item.kind,
      name:
        pickMenuTranslation(item as unknown as Record<string, unknown>, "name", locale) ??
        item.name,
      price: localizePriceString(item.price, locale),
      description: pickMenuTranslation(
        item as unknown as Record<string, unknown>,
        "description",
        locale,
      ),
      allergens: item.allergens,
      priceColumns: localizePriceColumns(item.priceColumns, locale),
    })),
  }));
}

export const FALLBACK_MENU: MenuCategoryData[] = resolveFallbackMenu("fr");
